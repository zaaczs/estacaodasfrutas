const TOKEN_RE = /[A-Za-zÀ-ÿ]+/g;

function aplicarCaixa(token: string, corrigido: string): string {
  const maiusculo = token.toLocaleUpperCase("pt-BR");
  if (token === maiusculo) return corrigido;
  if (token === token.toLocaleLowerCase("pt-BR")) {
    return corrigido.toLocaleLowerCase("pt-BR");
  }
  return corrigido;
}

/** Corrige a acentuação de um nome sem mudar números, pontuação ou palavras já corretas. */
export function corrigirAcentuacaoNome(nome: string): string {
  return nome.replace(TOKEN_RE, (token) => {
    const chave = token.toLocaleUpperCase("pt-BR");
    const corrigido = CORRECOES_PT_BR[chave];
    if (!corrigido || corrigido === chave) return token;
    return aplicarCaixa(token, corrigido);
  });
}
